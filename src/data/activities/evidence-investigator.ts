export type ItemKind = 'image' | 'text' | 'audio';

export interface EvidenceItem {
  id: string;
  kind: ItemKind;
  title: string;
  /** Emoji stand-in for the artwork, or the text of the passage. */
  display: string;
  /** Describes what is visible, for anyone using a screen reader. */
  label: string;
  /** Observations that are genuinely present in this item. */
  relevant: string[];
  /**
   * Conclusions that are defensible from the content alone. "Definitely"
   * answers never appear here — that is the whole lesson.
   */
  acceptable: ConclusionId[];
  /** What was actually true, revealed after the child has committed. */
  truth: string;
  teaching: string;
}

