/**
 * AI Evidence Investigator — the independent mission for Course 1, Lesson 3.
 *
 * The point of this activity is a habit of speech: *"It might be AI-generated
 * because…"* rather than *"AI definitely made this."* So the scoring is
 * deliberately shaped against overconfidence — a "definitely" answer is never
 * accepted from appearance alone, however good the observations are.
 *
 * Two of the six items really are human-made and two are genuinely unknowable.
 * If every item were AI, a child would learn to answer "AI" every time and
 * still score well, which teaches the opposite of the lesson.
 */

